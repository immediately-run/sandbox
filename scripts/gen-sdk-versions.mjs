#!/usr/bin/env node
/* eslint-disable no-console -- build-time CLI script: console is the output channel. */
// Generate src/generated/sdkVersions.ts at build time.
//
// Sandbox stamps the SDK *protocol* version into its host handshake
// (SDK_PACKAGING_SPEC §6, T45) — the wire-compatibility contract the host
// version-checks. This is a single compile-time string; there is no reason to
// pull the whole `@immediately-run/sdk` barrel (React components and all) into
// the bundle, nor to take a build-time dependency on the SDK's built `dist/`. We
// read it straight from the SDK's *source* in the sibling checkout, exactly as
// the deploy already reads DEFAULT_SDK_VERSION/floor from bundler.ts. (The SDK
// *package* version is intentionally NOT emitted — it gated nothing and, baked
// from the build-time checkout, never matched the per-app resolved SDK anyway.)
//
// Sibling layout is guaranteed locally and in the deploy (the orchestrator
// checks out `src/immediately-run-sdk` next to `src/sandbox`). Fails loudly if
// the sibling is absent rather than emitting a wrong/empty value.
import { readFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const sandboxRoot = resolve(here, '..');
const sdkRoot = resolve(sandboxRoot, '../immediately-run-sdk');
const out = resolve(sandboxRoot, 'src/generated/sdkVersions.ts');

function fail(msg) {
  console.error(`gen-sdk-versions: ${msg}`);
  process.exit(1);
}

// The deploy + local monorepo check out `immediately-run-sdk` next to the
// sandbox repo, so we read the authoritative value from source there. A
// standalone build (e.g. the single-repo CI) has no sibling — in that case keep
// the committed snapshot of src/generated/sdkVersions.ts (it is refreshed by the
// deploy build, which always has the sibling). Only fail if there is neither a
// sibling to read from nor an existing snapshot to fall back to.
if (!existsSync(sdkRoot)) {
  if (existsSync(out)) {
    console.log(
      `gen-sdk-versions: SDK sibling absent at ${sdkRoot}; keeping committed ${out}.`,
    );
    process.exit(0);
  }
  fail(
    `SDK sibling checkout not found at ${sdkRoot} and no committed ${out} to fall back to.`,
  );
}

// SDK_PROTOCOL_VERSION — a hand-maintained const in the SDK runtime source.
const runtimeSrc = resolve(sdkRoot, 'src/runtime.ts');
let protocolVersion;
try {
  const m = readFileSync(runtimeSrc, 'utf8').match(
    /SDK_PROTOCOL_VERSION\s*=\s*['"]([^'"]+)['"]/,
  );
  protocolVersion = m && m[1];
} catch (err) {
  fail(`could not read ${runtimeSrc}: ${err.message}`);
}
if (!protocolVersion) {
  fail(`could not find "SDK_PROTOCOL_VERSION = '...'" in ${runtimeSrc}.`);
}

const body = `// @generated by scripts/gen-sdk-versions.mjs — DO NOT EDIT.
// Sourced at build time from the sibling immediately-run-sdk checkout
// (the SDK_PROTOCOL_VERSION const in src/runtime.ts).
// Run \`npm run gen:sdk-versions\` (or any \`npm run build\`) to refresh.
export const SDK_PROTOCOL_VERSION = '${protocolVersion}';
`;

// Write only when changed so a clean build against a matching SDK never dirties
// the tree.
mkdirSync(dirname(out), { recursive: true });
const prev = existsSync(out) ? readFileSync(out, 'utf8') : null;
if (prev !== body) {
  writeFileSync(out, body);
  console.log(`gen-sdk-versions: wrote ${out} (SDK_PROTOCOL_VERSION=${protocolVersion})`);
} else {
  console.log(`gen-sdk-versions: up to date (SDK_PROTOCOL_VERSION=${protocolVersion})`);
}
