#!/usr/bin/env node
/*
 * Bake the runtime's embedded transpiler toolchainHash (PRETRANSPILED_ARTIFACTS_SPEC
 * §4.4) into src/bundler/artifacts/embeddedToolchainHash.ts. The runtime compares
 * this (plus TRANSPILER_VERSION) against an artifact index's `toolchain` and ignores
 * all artifacts on either mismatch (§5.1). It MUST be computed over the INSTALLED
 * @immediately-run/transpiler (= the published npm tarball) by the §4.4 canonical
 * recipe — never a local rebuild — so it matches the hash the CLI stamps into the
 * index. The deploy asserts parity against the published artifact (G2-8).
 *
 * Runs in `prebuild`; the generated file is committed so jest + the bundler see it
 * without a build.
 *
 * `--check` (R3-838): the drift gate. Regenerates the body and DIFFS it against
 * the committed file, writing nothing — until this leg existed, the committed
 * copy could drift from the installed pin for months invisibly (main carried the
 * 0.9.0 hash under a 0.9.1 pin from 1a8bc8d until R3-814's regenerate): jest and
 * `npm run dev` read the COMMITTED copy, so a drifted tree mis-accepts/mis-rejects
 * artifact indexes in exactly the runs that never build. Exit 1 names the fix.
 * `--self-test` proves the gate can fail (a corrupted committed file is detected)
 * without touching the real file.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

import { computeToolchainHash } from '@immediately-run/transpiler';

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('@immediately-run/transpiler/package.json'));

// Walk the installed package dir (= extracted published tarball), keyed by
// package-relative path. Mirrors the CLI's collectPackageFiles.
function collect(dir, base = dir, out = new Map()) {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules') continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) collect(full, base, out);
    else out.set(relative(base, full).split(sep).join('/'), readFileSync(full));
  }
  return out;
}

const hash = await computeToolchainHash(collect(pkgDir));

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src', 'bundler', 'artifacts', 'embeddedToolchainHash.ts');
const bodyFor = (h) =>
  `// GENERATED by scripts/gen-toolchain-hash.mjs — do not edit by hand.\n` +
  `// The §4.4 toolchainHash of the installed @immediately-run/transpiler (= the\n` +
  `// published tarball). Regenerated on every build (prebuild). The deploy asserts\n` +
  `// this equals the hash the CLI stamps into artifact indexes (G2-8).\n\n` +
  `export const EMBEDDED_TOOLCHAIN_HASH = '${h}';\n`;
const body = bodyFor(hash);

if (process.argv.includes('--self-test')) {
  // A gate that cannot fail is not a gate: the drifted-copy case must be
  // detected (and the clean case must pass — the same comparison the real
  // check runs).
  const committed = readFileSync(out, 'utf8');
  if (committed !== body) {
    console.error(
      'self-test: FAIL — the committed copy already drifts; run `npm run gen:toolchain-hash` and commit, then re-run',
    );
    process.exit(1);
  }
  if (committed === bodyFor('0'.repeat(64))) {
    console.error('self-test: FAIL — a corrupted hash was NOT detected');
    process.exit(1);
  }
  console.log('self-test: PASS — clean tree passes, a drifted hash is detected');
  process.exit(0);
}

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    /* first run */
  }
  if (current !== body) {
    console.error(
      `check:toolchain-hash: DRIFT — the committed embeddedToolchainHash.ts does not match the installed ` +
        `@immediately-run/transpiler pin (expected hash ${hash}). Fix: \`npm run gen:toolchain-hash\` and commit the result.`,
    );
    process.exit(1);
  }
  console.log(`check:toolchain-hash: committed == installed (${hash})`);
  process.exit(0);
}

let current = '';
try {
  current = readFileSync(out, 'utf8');
} catch {
  /* first run */
}
if (current !== body) {
  writeFileSync(out, body);
  console.log(`Baked EMBEDDED_TOOLCHAIN_HASH=${hash} -> ${out}`);
} else {
  console.log(`EMBEDDED_TOOLCHAIN_HASH already ${hash} — unchanged.`);
}
